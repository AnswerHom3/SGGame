local ORDER = {
    "light1",
    "light2",
    "light3",
    "light1_recover",
    "light2_recover",
    "light3_recover",
}

function AtkLightConfig.frame(clip, index)
    local row = AtkLightConfig.frames[clip]
    if row == nil or index == nil then
        return nil
    end
    return row[index + 1]
end

function AtkLightConfig.allPaths()
    local list = {}
    for _, name in ipairs(ORDER) do
        local row = AtkLightConfig.frames[name]
        for i = 1, #row do
            list[#list + 1] = row[i]
        end
    end
    return list
end

return AtkLightConfig
